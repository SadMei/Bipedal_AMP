"""Export a standard-URDF, zero-pose visualization of the mounted ankle links.

Ordinary URDF viewers do not solve nonlinear loop constraints. New preview
links are deliberately FIXED at ankle pitch=roll=0, not actuated or simulated.
Never use this file for training; the dynamic closed chain is in the MJCF.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import warnings
import xml.etree.ElementTree as ET

import numpy as np
from scipy.spatial.transform import Rotation

if __package__:
    from ._paths import URDF
    from .real_ankle import Geometry, RobotCore, point_z, vec, xml_string
else:
    from _paths import URDF
    from real_ankle import Geometry, RobotCore, point_z, vec, xml_string

SOURCE = URDF
OUTPUT = SOURCE.with_name("export_closed_ankle_preview.urdf")
COLORS = {"long": ".15 .55 .95 1", "short": ".98 .48 .12 1", "foot": ".15 .85 .3 1"}


def origin(parent, position, rotation=None):
    # Cylinders aligned with +X legitimately have pitch=pi/2. RPY is then not
    # unique; scipy's yaw=0 representative is still an exact valid transform.
    with warnings.catch_warnings():
        warnings.filterwarnings("ignore", message="Gimbal lock detected.*", category=UserWarning)
        rpy = np.zeros(3) if rotation is None else Rotation.from_matrix(rotation).as_euler("xyz")
    ET.SubElement(parent, "origin", xyz=vec(position), rpy=vec(rpy))


def fixed_link(root, name, parent, position, rotation=None):
    link = ET.SubElement(root, "link", name=name)
    joint = ET.SubElement(root, "joint", name=f"{name}_fixed", type="fixed")
    ET.SubElement(joint, "parent", link=parent)
    ET.SubElement(joint, "child", link=name)
    origin(joint, position, rotation)
    return link


def visual(link, name, position, shape, attributes, color, rotation=None):
    vis = ET.SubElement(link, "visual", name=name)
    origin(vis, position, rotation)
    ET.SubElement(ET.SubElement(vis, "geometry"), shape, **attributes)
    material = ET.SubElement(vis, "material", name=f"closed_preview_{color}")
    ET.SubElement(material, "color", rgba=COLORS[color])


def segment(link, endpoint, radius, color):
    endpoint = np.asarray(endpoint)
    visual(link, "segment", endpoint / 2, "cylinder",
           {"radius": str(radius), "length": str(np.linalg.norm(endpoint))},
           color, point_z(endpoint))
    for name, position in (("start", np.zeros(3)), ("end", endpoint)):
        visual(link, name, position, "sphere", {"radius": ".005"}, color)


def build_preview(core, output=OUTPUT, source=SOURCE):
    source, output = Path(source).resolve(), Path(output).resolve()
    if source == output:
        raise ValueError("The preview must never overwrite the training URDF")
    root = ET.parse(source, parser=ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))).getroot()
    root.set("name", "bsrl_closed_ankle_ZERO_POSE_VISUAL_PREVIEW_ONLY")
    root.insert(0, ET.Comment(
        "\n    VIEWER PREVIEW ONLY - NOT A DYNAMIC CLOSED-CHAIN URDF.\n"
        "    Generated by Bipedal_AMP/scripts/tools/parallel_ankle/build_preview_urdf.py.\n"
        "    Set original ankle pitch and roll to 0 to inspect mounting.\n"
        "    Blue=long branch, orange=short branch, green=foot attachment.\n"
        "    New links are fixed zero-pose visuals, without collision or inertia.\n"
        "    Ordinary viewers cannot keep a nonlinear loop closed when ankles move.\n"
        "    Original CAD rods are still present for comparison; meshes are unchanged.\n"
        "    All original joint axes/origins/limits and inertias are unchanged.\n"
        "    For closed-chain physics use parallel_ankle/bsrl_closed_ankles.xml.\n  "
    ))
    # Keep the file portable with its existing meshes; do not bake workspace paths.
    for mesh in root.findall(".//mesh"):
        filename = mesh.get("filename")
        if "://" in filename:
            continue
        mesh_path = (source.parent / filename).resolve()
        if not mesh_path.is_file():
            raise FileNotFoundError(mesh_path)
        mesh.set("filename", os.path.relpath(mesh_path, output.parent))
    for side in ("right", "left"):
        g = Geometry(side, core)
        ankle = root.find(f"joint[@name='joint_{side}_ankle_pitch']")
        roll = root.find(f"joint[@name='joint_{side}_ankle_roll']")
        for joint, axis in ((ankle, [0, 1, 0]), (roll, [1, 0, 0])):
            np.testing.assert_allclose(np.fromstring(joint.find("origin").get("rpy"), sep=" "), 0)
            np.testing.assert_allclose(np.fromstring(joint.find("axis").get("xyz"), sep=" "), axis)
        np.testing.assert_allclose(np.fromstring(roll.find("origin").get("xyz"), sep=" "), 0)
        ankle_origin = np.fromstring(ankle.find("origin").get("xyz"), sep=" ")
        for i, branch in enumerate(("long", "short")):
            prefix = f"preview_{side}_{branch}"
            rotation = g.crank_rotation(i, 0.)
            crank_end = g.crank_end(i, 0.)
            offset = g.crank_offsets[i]
            rod_vector = g.mounts[i] - crank_end
            rod_rotation = point_z(rod_vector)
            length = np.linalg.norm(rod_vector)
            np.testing.assert_allclose(length, g.l4[i], atol=1e-12, rtol=0)
            crank = fixed_link(root, f"{prefix}_crank", f"link_{side}_shank",
                               ankle_origin + g.pivots[i], rotation)
            segment(crank, offset, .004, branch)
            rod = fixed_link(root, f"{prefix}_rod", crank.get("name"), offset,
                             rotation.T @ rod_rotation)
            segment(rod, [0, 0, length], .003, branch)
            foot = fixed_link(root, f"{prefix}_foot_mount", f"link_{side}_ankle_roll", g.mounts[i])
            visual(foot, "foot_connection", np.zeros(3), "sphere", {"radius": ".0065"}, "foot")
    return '<?xml version="1.0" encoding="utf-8"?>\n' + xml_string(root) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    xml = build_preview(RobotCore(), args.output)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(xml)
    print(args.output.resolve())
    print("Visual preview only: keep ankle pitch/roll at zero; no dynamic loop constraints.")


if __name__ == "__main__":
    main()
